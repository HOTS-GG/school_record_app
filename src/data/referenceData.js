/**
 * 영역명에서 과목을 추론하여 세부능력 달성 기준을 반환
 * @param {string} areaName 영역명 (예: "수학", "1학년 수학", "수학I")
 * @returns {{ subject: string, criteria: object } | null}
 */
export function getSubjectCriteria(areaName) {
  if (!areaName) return null
  const lower = areaName.toLowerCase().replace(/\s/g, '')
  for (const [subject, keywords] of Object.entries(SUBJECT_KEYWORDS)) {
    if (keywords.some(k => lower.includes(k.toLowerCase()))) {
      return { subject, criteria: SUBJECT_CRITERIA[subject] }
    }
  }
  return null
}

/**
 * 세부능력 기준을 AI 프롬프트용 텍스트로 변환
 * @param {string} areaName
 * @returns {string}  빈 문자열이면 해당 과목 없음
 */
export function buildCriteriaPrompt(areaName) {
  const result = getSubjectCriteria(areaName)
  if (!result) return ''
  const { subject, criteria } = result
  return [
    `[${subject} 과목 세부능력 달성 기준 참고]`,
    `상 수준: ${criteria.상.join(' / ')}`,
    `중 수준: ${criteria.중.join(' / ')}`,
    `하 수준: ${criteria.하.join(' / ')}`,
  ].join('\n')
}

/**
 * 행동발달 특성을 AI 프롬프트용 텍스트로 변환
 * @param {string[]|null} selectedCategories null이면 전체 포함
 * @returns {string}
 */
export function buildBehaviorPrompt(selectedCategories = null) {
  const entries = Object.entries(BEHAVIORAL_TRAITS).filter(([cat]) =>
    !selectedCategories || selectedCategories.includes(cat)
  )
  if (entries.length === 0) return ''
  const lines = ['[행동발달 특성 참고 목록]']
  for (const [category, traits] of entries) {
    const names = traits.map(t => `${t.name}(${t.desc})`).join(', ')
    lines.push(`${category}: ${names}`)
  }
  return lines.join('\n')
}
