function toggle(id) {
  openSection.value = openSection.value === id ? null : id
}

function scrollTo(id) {
  openSection.value = id
  setTimeout(() => {
    const el = contentRef.value?.querySelector(`[data-id="${id}"]`)
    if (el && contentRef.value) {
      const offset = el.getBoundingClientRect().top - contentRef.value.getBoundingClientRect().top
      contentRef.value.scrollTo({top: contentRef.value.scrollTop + offset - 24, behavior: 'smooth'})
    }
  }, 220)
}
</script>

